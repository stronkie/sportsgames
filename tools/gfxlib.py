def speak(phon, rate=6000, speed=1.0):
    x = voice.say(phon)
    if rate != 8000:
        idx = np.arange(0, len(x), 8000 / rate); x = np.interp(idx, np.arange(len(x)), x)
    if speed != 1.0:
        idx = np.arange(0, len(x), speed); x = np.interp(idx, np.arange(len(x)), x)
    return tosamp(x)

